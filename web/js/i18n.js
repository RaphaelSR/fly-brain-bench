export const LOCALES = { en: EN, pt: PT, es: ES };
let current = 'en';

export function detectLocale() {
  try {
    const saved = localStorage.getItem('fbb.lang');
    if (saved && LOCALES[saved]) return saved;
  } catch (_) { /* private mode */ }
  const nav = (navigator.languages || [navigator.language || 'en']).map(s => s.slice(0, 2).toLowerCase());
  return nav.find(l => LOCALES[l]) || 'en';
}

export function setLocale(code) {
  if (!LOCALES[code]) return;
  current = code;
  try { localStorage.setItem('fbb.lang', code); } catch (_) { /* private mode */ }
  document.documentElement.lang = code;
}

export const getLocale = () => current;

export function t(key, vars) {
  let s = LOCALES[current][key];
  if (s === undefined) s = LOCALES.en[key];
  if (s === undefined) return key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

/* Applies translations to any element carrying data-i18n / data-i18n-html. */
export function applyDom(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
}
